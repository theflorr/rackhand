from __future__ import annotations

from rich.text import Text
from textual import on
from textual.app import ComposeResult
from textual.binding import Binding
from textual.containers import Horizontal, Vertical
from textual.screen import ModalScreen
from textual.widgets import Button, Checkbox, Input, Label, Static, TextArea

from models import ApprovalDecision, ProposedChange, Risk, RISK_LABEL
from ui.styles import pill


class ApprovalModal(ModalScreen[ApprovalDecision]):
    """Human-in-the-loop gate for every change the agent proposes."""
    BINDINGS = [Binding("escape", "reject", "Cancel")]

    def __init__(self, change: ProposedChange, default_save: bool = False) -> None:
        super().__init__()
        self.change = change
        self.default_save = default_save

    def compose(self) -> ComposeResult:
        c = self.change
        with Vertical(id="approval"):
            with Vertical(id="ap-header"):
                hdr = Text()
                hdr.append("› ", style="bold #cccccc")
                hdr.append(c.title or "Proposed Configuration Change", style="bold white")
                yield Static(hdr, id="ap-title")

                risk_kind = {"read": "ok", "config": "warn", "danger": "err"}[c.risk.value]
                sub = Text()
                sub.append(f"Target: {c.device}  ·  ", style="dim #888888")
                sub.append_text(pill(RISK_LABEL[c.risk], risk_kind))
                yield Static(sub, id="ap-device-row")

            # Small note on why & what generated by the agent
            if c.rationale:
                with Vertical(id="ap-note-box"):
                    yield Label("WHY & WHAT", id="ap-note-lbl")
                    yield Static(c.rationale.strip(), id="ap-note-text")

            yield Label(f"COMMANDS TO APPLY ({len(c.commands)})", id="ap-cmds-lbl")
            yield TextArea("\n".join(c.commands), id="ap-cmds")

            yield Checkbox("Save running-config to NVRAM (write memory)", self.default_save, id="ap-save")

            if c.risk is Risk.DANGER:
                yield Label(f"Safety lock: enter hostname ({c.device}) to confirm", classes="warn")
                yield Input(placeholder=c.device, id="ap-confirm")

            with Horizontal(classes="ap-buttons"):
                yield Button("Cancel", id="ap-reject")
                yield Button("Apply to device", id="ap-apply", disabled=c.risk is Risk.DANGER)

    @on(Input.Changed, "#ap-confirm")
    def _confirm_typed(self, ev: Input.Changed) -> None:
        self.query_one("#ap-apply", Button).disabled = ev.value.strip() != self.change.device

    @on(Button.Pressed, "#ap-apply")
    def _apply(self) -> None:
        lines = [ln.strip() for ln in self.query_one("#ap-cmds", TextArea).text.splitlines() if ln.strip()]
        save_nvram = self.query_one("#ap-save", Checkbox).value
        self.dismiss(ApprovalDecision(True, lines, save_nvram))

    @on(Button.Pressed, "#ap-reject")
    def action_reject(self) -> None:
        self.dismiss(ApprovalDecision(False))
